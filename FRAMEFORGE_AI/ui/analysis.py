"""Script Analysis page: upload tab, AI pipeline tab, story analysis tab."""
import pandas as pd
import streamlit as st

from config.settings import get_settings
from core import pipeline, production_planner
from ui import theme, upload
from ui.common import STRETCH, flash, get_client, has_api_key, require_project, safe

STORY_TEXT = [("synopsis", "Synopsis"), ("genre", "Genre"), ("main_plot", "Main plot"), ("protagonist", "Protagonist"),
              ("antagonist", "Antagonist"), ("beginning", "Beginning"), ("middle", "Middle"), ("ending", "Ending")]
STORY_LISTS = [("subplots", "Subplots"), ("supporting_characters", "Supporting characters"), ("major_events", "Major events"),
               ("turning_points", "Turning points"), ("emotional_sequences", "Emotional / dramatic sequences"),
               ("uncertainty_notes", "Uncertainty notes")]


def render(repo, pid):
    st.title("Script Analysis")
    require_project(repo, pid)
    t1, t2, t3 = st.tabs(["1. Upload & Preview", "2. AI Analysis", "3. Story Analysis"])
    with t1:
        upload.render_upload(repo, pid)
    with t2:
        _run_tab(repo, pid)
    with t3:
        _story_tab(repo, pid)


def _run_tab(repo, pid):
    doc = repo.latest_document(pid)
    if not doc:
        st.info("Upload a screenplay first.")
        return
    st.info("Privacy: the screenplay text is sent to NVIDIA's hosted NIM API for analysis. "
            "Do not upload material you are not allowed to share with an external service.")
    stages = repo.get_stages(pid)
    cols = st.columns(4)
    for col, name in zip(cols, ["chunking", "scene_extraction", "registers", "story_analysis"]):
        s = stages.get(name, {"status": "PENDING", "message": ""})
        kind = {"DONE": "ok", "FAILED": "bad", "RUNNING": "run"}.get(s["status"], "warn")
        col.markdown(f"**{name.replace('_', ' ').title()}**<br>{theme.pill(s['status'], kind)}<br>"
                     f"<span style='font-size:.72rem;color:#8C97BD'>{s.get('message') or ''}</span>", unsafe_allow_html=True)
    st.write("")
    existing = repo.list_scenes(pid)
    confirm = True
    if existing:
        confirm = st.checkbox("Re-analysing replaces the current scenes, registers and schedule, including manual edits.")
    if not has_api_key():
        st.error("No NVIDIA API key configured. Add NVIDIA_API_KEY to .env or enter one for this session in Settings.")
    if st.button("Analyse Script", type="primary", disabled=not (confirm and has_api_key())):
        _do_analyse(repo, pid, fresh=True)
    chunks = repo.list_chunks(pid)
    if chunks:
        failed = [c for c in chunks if c["status"] != "DONE"]
        df = pd.DataFrame([{"chunk": c["chunk_id"], "status": c["status"], "pages": f"{c['payload']['page_start']}-{c['payload']['page_end']}",
                            "scene blocks": len({u["block_id"] for u in c["payload"]["units"]}), "attempts": c["attempts"],
                            "error": c["error"] or ""} for c in chunks])
        st.dataframe(df, hide_index=True, **STRETCH)
        c1, c2, c3 = st.columns(3)
        if c1.button("Retry failed chunks", disabled=not failed or not has_api_key()):
            _do_analyse(repo, pid, fresh=False)
        if c2.button("Re-run story analysis", disabled=not existing or not has_api_key()):
            with st.spinner("Analysing story..."):
                if safe(pipeline.run_story, repo, pid, get_client()):
                    st.success("Story analysis updated.")
        if c3.button("Rebuild registers from scenes", disabled=not existing):
            production_planner.rebuild_registers(repo, pid)
            st.success("Characters, locations and resources rebuilt (your manual edits are kept).")


def _do_analyse(repo, pid, fresh):
    bar = st.progress(0.0, text="Preparing...")

    def cb(i, n, cid, status):
        bar.progress(i / max(n, 1), text=f"Chunk {i}/{n} ({cid}): {status}")
    try:
        out = pipeline.analyse(repo, pid, get_client(), get_settings(), cb, fresh=fresh)
    except Exception as exc:  # noqa: BLE001
        st.error(f"Analysis stopped: {exc}")
        return
    if out["assembled"]:
        a = out["assembled"]
        flash("success", f"Extracted {a['scenes']} scenes ({a['flagged']} flagged for review). Story analysis: {out['story'] or 'failed'}.")
    for e in out["errors"]:
        flash("error", e)
    st.rerun()


def _story_tab(repo, pid):
    a = repo.get_analysis(pid)
    if not a.get("synopsis"):
        st.info("Story analysis has not been generated yet. Run the AI analysis first.")
        return
    st.caption("Generated by AI from chunk summaries; edit anything that is wrong. " + a.get("runtime_basis", ""))
    with st.form("story_edit"):
        vals = {k: st.text_area(label, a.get(k, ""), height=90 if k in ("synopsis", "main_plot", "beginning", "middle", "ending") else 60)
                for k, label in STORY_TEXT}
        lists = {k: st.text_area(f"{label} (one per line)", "\n".join(a.get(k, [])), height=90) for k, label in STORY_LISTS}
        if st.form_submit_button("Save story analysis", type="primary"):
            vals.update({k: [x.strip() for x in v.splitlines() if x.strip()] for k, v in lists.items()})
            repo.update_analysis(pid, **vals)
            st.success("Saved.")
